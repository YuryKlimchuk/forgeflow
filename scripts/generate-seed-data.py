def build_catalog(assemblies):
    catalog = []
    for number, name in standart_items():
        catalog.append({"number": number, "name": name, "type": "STANDART"})
    for number, name in buy_items():
        catalog.append({"number": number, "name": name, "type": "BUY"})
    for number, name in part_items():
        catalog.append({"number": number, "name": name, "type": "PART"})
    for number, name in vzk_items():
        catalog.append({"number": number, "name": name, "type": "VZK"})
    for number, name in assemblies:
        catalog.append({"number": number, "name": name, "type": "ASSEMBLY"})
    return catalog


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="seed-data")
    args = parser.parse_args()

    os.makedirs(args.out, exist_ok=True)

    assemblies, specifications = assembly_hierarchy()
    catalog = build_catalog(assemblies)

    with open(os.path.join(args.out, "catalog.json"), "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)
        f.write("\n")

    with open(os.path.join(args.out, "specifications.json"), "w", encoding="utf-8") as f:
        json.dump(specifications, f, ensure_ascii=False, indent=2)
        f.write("\n")

    with open(os.path.join(args.out, "patterns.json"), "w", encoding="utf-8") as f:
        json.dump(PATTERNS, f, ensure_ascii=False, indent=2)
        f.write("\n")


if __name__ == "__main__":
    main()
